#!/usr/bin/env python3
"""Shared deterministic ship-check checks used by the CLI and push gate."""
from __future__ import annotations

import re
import subprocess
from pathlib import Path, PurePosixPath

VERSION = "ship-check-0.2"
PRODUCTION_LIMIT = 600
WORKING_DOC_PATTERNS = (
    "docs/plans/*",
    "docs/plans/**",
    "docs/superpowers/*",
    "docs/superpowers/**",
    ".superpowers/*",
    ".superpowers/**",
    "*-plan.md",
    "**/*-plan.md",
    "*-design.md",
    "**/*-design.md",
    "*test-audit*.md",
    "**/*test-audit*.md",
    "solutions/*",
    "solutions/**",
)
TEST_PARTS = {"test", "tests", "spec", "specs", "__tests__", "fixtures", "fixture"}
DOC_PARTS = {"doc", "docs", "documentation"}
TEST_SUFFIXES = ("_test.py", "_test.go", ".test.js", ".test.ts", ".spec.js", ".spec.ts")
DOC_SUFFIXES = (".md", ".rst", ".adoc", ".txt")
AGENT_WORDS = r"(?:agent|tool|ai|bot|mistral\s+vibe|vibe|claude|codex|copilot|chatgpt|openai|gemini|cursor)"
ATTRIBUTION_PATTERNS = (
    re.compile(rf"^Co-Authored-By:.*\b{AGENT_WORDS}\b", re.I | re.M),
    re.compile(r"^Generated by\b.*", re.I | re.M),
    re.compile(r"^Generated with\b.*", re.I | re.M),
    re.compile(r"^🤖.*(?:Claude|Vibe|Codex|AI|CE)", re.I | re.M),
    re.compile(r"\b(?:Claude|Vibe|Codex|CE)\s*(?:badge|generated|authored)\b", re.I),
)


def run_git(repo: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", *args], cwd=repo, text=True, capture_output=True, check=check)


def git_out(repo: Path, *args: str) -> str:
    return run_git(repo, *args).stdout.strip()


def resolve_base(repo: Path, base: str) -> str:
    try:
        git_out(repo, "rev-parse", "--verify", base)
        return base
    except subprocess.CalledProcessError:
        if base == "origin/main":
            git_out(repo, "rev-parse", "--verify", "main")
            return "main"
        raise


def commit_messages(repo: Path, base: str, head: str = "HEAD") -> list[tuple[str, str]]:
    raw = git_out(repo, "log", "--format=%H%x00%B%x00%x1e", f"{base}..{head}")
    commits: list[tuple[str, str]] = []
    for record in raw.split("\x1e"):
        record = record.strip("\n\x00")
        if not record:
            continue
        sha, _, message = record.partition("\x00")
        commits.append((sha, message.strip()))
    return commits


def status(name: str, outcome: str, summary: str, **extra) -> dict:
    return {"name": name, "status": outcome, "summary": summary, **extra}


def check_attribution(repo: Path, base: str, head: str = "HEAD") -> dict:
    offenders = []
    for sha, message in commit_messages(repo, base, head):
        for pattern in ATTRIBUTION_PATTERNS:
            match = pattern.search(message)
            if match:
                offenders.append({"commit": sha, "match": match.group(0).strip()})
                break
    if offenders:
        first = offenders[0]["match"]
        return status(
            "attribution",
            "fail",
            f"{len(offenders)} commit message(s) contain AI/tool attribution; first: {first}",
            offenders=offenders,
        )
    return status("attribution", "pass", "no AI/tool attribution in commit messages")


def is_test_path(path: str) -> bool:
    p = PurePosixPath(path)
    return any(part in TEST_PARTS for part in p.parts[:-1]) or p.name.endswith(TEST_SUFFIXES) or p.name.startswith("test_")


def is_doc_path(path: str) -> bool:
    p = PurePosixPath(path)
    return any(part in DOC_PARTS for part in p.parts[:-1]) or p.name.endswith(DOC_SUFFIXES)


def has_size_justification(repo: Path, base: str, head: str = "HEAD") -> bool:
    return any(re.search(r"^Size-justification:\s*\S", message, re.I | re.M) for _, message in commit_messages(repo, base, head))


def numstat_split(repo: Path, base: str, head: str = "HEAD") -> dict:
    proc = run_git(repo, "diff", "--numstat", f"{base}...{head}")
    split = {"production": 0, "tests": 0, "docs": 0, "files": []}
    for line in proc.stdout.splitlines():
        fields = line.split("\t")
        if len(fields) < 3 or fields[0] == "-" or fields[1] == "-":
            continue
        added, deleted, path = int(fields[0]), int(fields[1]), fields[2]
        total = added + deleted
        kind = "tests" if is_test_path(path) else "docs" if is_doc_path(path) else "production"
        split[kind] += total
        split["files"].append({"path": path, "lines": total, "kind": kind})
    return split


def check_size(repo: Path, base: str, head: str = "HEAD") -> dict:
    split = numstat_split(repo, base, head)
    justified = has_size_justification(repo, base, head)
    production = split["production"]
    tests = split["tests"]
    if production > PRODUCTION_LIMIT and not justified:
        return status(
            "size",
            "fail",
            f"production lines {production} exceed {PRODUCTION_LIMIT} without Size-justification trailer; tests {tests}, docs {split['docs']}",
            split=split,
            size_justification=justified,
        )
    return status(
        "size",
        "pass",
        f"production lines {production}, tests {tests}, docs {split['docs']}"
        + ("; Size-justification present" if justified else ""),
        split=split,
        size_justification=justified,
    )


def matches_working_doc(path: str) -> bool:
    p = PurePosixPath(path)
    return any(p.match(pattern) for pattern in WORKING_DOC_PATTERNS)


def check_working_docs(repo: Path, base: str, head: str = "HEAD") -> dict:
    proc = run_git(repo, "diff", "--name-status", "--diff-filter=A", f"{base}...{head}")
    bad = []
    for line in proc.stdout.splitlines():
        fields = line.split("\t")
        if len(fields) >= 2 and matches_working_doc(fields[-1]):
            bad.append(fields[-1])
    if bad:
        return status("working_docs", "fail", f"working docs added on range: {', '.join(bad)}", paths=bad)
    return status("working_docs", "pass", "no working docs added on range", paths=[])


def deterministic_checks(repo: Path, base: str = "origin/main", head: str = "HEAD") -> list[dict]:
    base = resolve_base(repo, base)
    return [
        check_attribution(repo, base, head),
        check_size(repo, base, head),
        check_working_docs(repo, base, head),
    ]


def failed_checks(checks: list[dict]) -> list[dict]:
    return [check for check in checks if check["status"] == "fail"]
