import unittest

from analyze_comments import find_long_comment_blocks


class FindLongCommentBlocksTests(unittest.TestCase):
    def test_flags_three_consecutive_full_line_comments(self):
        source = """# Fetch the timeout.\n# Convert it to milliseconds.\n# Pass it to the client.\ntimeout = 1\n"""

        self.assertEqual(
            find_long_comment_blocks(source),
            [{"start_line": 1, "end_line": 3, "line_count": 3}],
        )

    def test_allows_two_line_comment(self):
        source = "# Non-obvious constraint.\n# Keep this operation ordered.\nrun()\n"

        self.assertEqual(find_long_comment_blocks(source), [])

    def test_ignores_hashes_in_strings_and_inline_comments(self):
        source = """value = "# not a comment"\na = 1  # first inline note\nb = 2  # second inline note\nc = 3  # third inline note\n"""

        self.assertEqual(find_long_comment_blocks(source), [])

    def test_directives_break_comment_runs(self):
        source = """# Explain one constraint.\n# Explain another constraint.\n# noqa: E501\n# Explain a final constraint.\n"""

        self.assertEqual(find_long_comment_blocks(source), [])

    def test_ignores_shebang_and_encoding_declaration(self):
        source = """#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\n# First useful note.\nprint("ok")\n"""

        self.assertEqual(find_long_comment_blocks(source), [])

    def test_ignores_license_and_generated_headers(self):
        source = """# Copyright 2026 Example Corp.\n# Licensed under the Apache License, Version 2.0.\n# SPDX-License-Identifier: Apache-2.0\nmodule_value = 1\n\n# This file is generated.\n# Do not edit this file manually.\n# Changes will be overwritten.\ngenerated_value = 2\n"""

        self.assertEqual(find_long_comment_blocks(source), [])

    def test_finds_comments_before_an_incomplete_token_stream(self):
        source = """# First narration.\n# Second narration.\n# Third narration.\nvalue = '''unfinished\n"""

        self.assertEqual(
            find_long_comment_blocks(source),
            [{"start_line": 1, "end_line": 3, "line_count": 3}],
        )


if __name__ == "__main__":
    unittest.main()
