#!/usr/bin/env python3
"""Find long runs of full-line Python comments in newly written text."""

from __future__ import annotations

import io
import json
import re
import sys
import tokenize
from collections.abc import Iterable
from typing import TypedDict


MINIMUM_COMMENT_LINES = 3

_DIRECTIVE_RE = re.compile(
    r"^#\s*(?:"
    r"noqa\b|"
    r"type:\s*ignore\b|"
    r"pyright:\s*ignore\b|"
    r"fmt:\s*(?:off|on)\b|"
    r"isort:\s*(?:skip|off|on)\b|"
    r"pragma:\s*no\s*cover\b|"
    r"coverage:\s*ignore\b|"
    r"ruff:\s*noqa\b"
    r")",
    re.IGNORECASE,
)
_ENCODING_RE = re.compile(r"^#.*coding[=:]\s*[-\w.]+", re.IGNORECASE)
_HEADER_MARKERS = (
    "copyright",
    "licensed under",
    "spdx-license-identifier",
    "this file is generated",
    "auto-generated",
    "autogenerated",
    "do not edit this file",
)


class CommentBlock(TypedDict):
    start_line: int
    end_line: int
    line_count: int


def _is_exempt_line(comment: str, line_number: int) -> bool:
    stripped = comment.strip()
    if line_number == 1 and stripped.startswith("#!"):
        return True
    if line_number <= 2 and _ENCODING_RE.match(stripped):
        return True
    return _DIRECTIVE_RE.match(stripped) is not None


def _is_exempt_block(comments: Iterable[str]) -> bool:
    text = "\n".join(comments).lower()
    return any(marker in text for marker in _HEADER_MARKERS)


def find_long_comment_blocks(
    source: str, minimum_lines: int = MINIMUM_COMMENT_LINES
) -> list[CommentBlock]:
    """Return long, consecutive runs of non-directive full-line comments.

    Tokenization deliberately excludes hashes inside strings and inline comments.
    Partial edit snippets are accepted: comments emitted before a lexical error are
    still checked.
    """
    comment_lines: list[tuple[int, str]] = []
    tokens = tokenize.generate_tokens(io.StringIO(source).readline)

    try:
        for token in tokens:
            if token.type != tokenize.COMMENT:
                continue
            line_number, column = token.start
            if token.line[:column].strip():
                continue
            if _is_exempt_line(token.string, line_number):
                continue
            comment_lines.append((line_number, token.string))
    except (tokenize.TokenError, IndentationError, SyntaxError):
        pass

    runs: list[list[tuple[int, str]]] = []
    for item in comment_lines:
        if not runs or item[0] != runs[-1][-1][0] + 1:
            runs.append([item])
        else:
            runs[-1].append(item)

    blocks: list[CommentBlock] = []
    for run in runs:
        if len(run) < minimum_lines or _is_exempt_block(comment for _, comment in run):
            continue
        blocks.append(
            {
                "start_line": run[0][0],
                "end_line": run[-1][0],
                "line_count": len(run),
            }
        )
    return blocks


def main() -> int:
    payload = json.load(sys.stdin)
    sources = payload.get("sources", [])
    if not isinstance(sources, list) or not all(isinstance(source, str) for source in sources):
        raise ValueError("sources must be a list of strings")
    json.dump(
        {"results": [find_long_comment_blocks(source) for source in sources]},
        sys.stdout,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
